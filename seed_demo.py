def seed():
    assert init_user_storage(), "Не удалось подключиться к базе. Проверьте .env и PostgreSQL."
    init_extra_tables()
    added = 0
    with db_cursor(commit=True) as cur:
        for title, genres, year, country, director, duration, actors in FILMS:
            cur.execute("SELECT 1 FROM films WHERE title = %s AND year = %s;", (title, year))
            if cur.fetchone():
                continue
            cur.execute("INSERT INTO films (title, genres, year, country, director, actors, duration, description) "
                        "VALUES (%s, %s, %s, %s, %s, %s, %s, %s);",
                        (title, genres, year, country, director, actors, duration, MARK))
            added += 1
        apps = 0
        for email, name, portfolio, about in DEMO_USERS:
            cur.execute("SELECT id FROM users WHERE email = %s;", (email,))
            row = cur.fetchone()
            if row is None:
                cur.execute("INSERT INTO users (email, password_hash, role, name) VALUES (%s, %s, 'viewer', %s) RETURNING id;",
                            (email, hash_password("demo12345"), name))
                row = cur.fetchone()
            cur.execute("SELECT 1 FROM author_applications WHERE user_id = %s;", (row["id"],))
            if not cur.fetchone():
                cur.execute("INSERT INTO author_applications (user_id, portfolio_url, about) VALUES (%s, %s, %s);",
                            (row["id"], portfolio, about))
                apps += 1
    print(f"Добавлено фильмов: {added}, заявок авторов: {apps}.")


def clear():
    with db_cursor(commit=True) as cur:
        cur.execute("DELETE FROM films WHERE description = %s;", (MARK,))
        n_films = cur.rowcount
        cur.execute("DELETE FROM users WHERE email LIKE 'demo\\_author%%@example.com';")
        n_users = cur.rowcount
    print(f"Удалено демо-фильмов: {n_films}, демо-пользователей: {n_users}.")


if __name__ == "__main__":
    clear() if "--clear" in sys.argv else seed()
